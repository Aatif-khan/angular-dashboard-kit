/**
 * Read-only status codes mapping standard REST communication outcomes.
 */
export const HTTP_STATUS = {
  OK: 200,
  CREATED: 201,
  ACCEPTED: 202,
  NO_CONTENT: 204,
  BAD_REQUEST: 400,
  UNAUTHORIZED: 401,
  FORBIDDEN: 403,
  NOT_FOUND: 404,
  CONFLICT: 409,
  UNPROCESSABLE_ENTITY: 422,
  INTERNAL_SERVER_ERROR: 500,
} as const;

/**
 * Type representing valid HTTP status code integer mappings.
 */
export type HttpStatus = typeof HTTP_STATUS[keyof typeof HTTP_STATUS];
